'use strict';
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const projectRoot=path.join(__dirname,'..');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'gia-pha-v1011-'));
fs.mkdirSync(path.join(tmp,'lib'),{recursive:true});
for(const name of ['db.js','security.js'])fs.copyFileSync(path.join(projectRoot,'lib',name),path.join(tmp,'lib',name));
try{
  const {Store}=require(path.join(tmp,'lib','db.js'));
  const store=new Store();
  const admin=store.ensureAdmin('admin','Regression-Password-2026!',false);
  const y=new Date().getFullYear();
  const p85=store.createPerson({full_name:'Người 85',gender:'female',birth_date:String(y-85),privacy_mode:'public'},admin.id);
  const p65=store.createPerson({full_name:'Người 65',gender:'male',birth_date:String(y-65),privacy_mode:'limited'},admin.id);
  store.createPerson({full_name:'Người 45',gender:'female',birth_date:String(y-45),privacy_mode:'public'},admin.id);
  store.createPerson({full_name:'Người thọ 72',gender:'male',birth_date:'1948',death_date:'2020',is_deceased:true,privacy_mode:'private'},admin.id);
  store.createPerson({full_name:'Người 18',gender:'female',birth_date:String(y-18),privacy_mode:'public'},admin.id);
  store.createPerson({full_name:'Trẻ 10',gender:'male',birth_date:String(y-10),privacy_mode:'public'},admin.id);
  store.createPerson({full_name:'Chưa rõ tuổi',gender:'female',privacy_mode:'public'},admin.id);
  store.createPerson({full_name:'Chưa rõ năm mất',gender:'male',birth_date:'1950',is_deceased:true,privacy_mode:'public'},admin.id);
  const publicPeople=store.listPeople({publicOnly:true});
  const limited=publicPeople.find(p=>p.id===p65.id);
  assert.equal(limited.birth_date,null,'Limited vẫn phải ẩn ngày sinh công khai');
  assert.equal(limited.age_years,65,'Tuổi dẫn xuất phải có để thống kê sau khi ẩn ngày sinh');
  const stats=store.treeStats(publicPeople);
  const band=(min,max)=>stats.age_bands.find(b=>b.min===min&&b.max===max);
  assert.equal(band(80,null).total,1,'Nhóm 80+ phải đếm đúng người từ 80 tuổi trở lên');
  assert.equal(band(60,80).total,2,'Nhóm 60-80 phải gồm người 65 và người thọ 72');
  assert.equal(band(60,80).living,1,'Nhóm 60-80 phải tách đúng người còn sống');
  assert.equal(band(60,80).deceased,1,'Nhóm 60-80 phải tách đúng người đã mất');
  assert.equal(band(40,60).total,1,'Nhóm 40-60 phải đếm đúng');
  assert.equal(band(16,20).total,1,'Nhóm 16-20 phải đếm đúng');
  assert.equal(band(0,16).total,1,'Nhóm 0-16 phải đếm đúng và không tính người chưa rõ tuổi như 0 tuổi');
  assert.equal(stats.age_unknown.total,2,'Nhóm Không rõ phải gồm người thiếu năm sinh và người đã mất thiếu năm mất');
  assert.equal(stats.age_unknown.living,1,'Nhóm Không rõ phải tách đúng người còn sống');
  assert.equal(stats.age_unknown.deceased,1,'Nhóm Không rõ phải tách đúng người đã mất');
  assert.equal(store.getSetting('tree_title_font_size'),'28');
  assert.equal(store.getSetting('clan_name_font_size'),'66');
  assert.equal(store.getSetting('footer_author_font'),'system');
  const updated=store.updateSettings({tree_title_font_size:'30',clan_name_font_size:'72',tree_subtitle:'Dòng một\nDòng hai'},admin.id);
  assert.equal(updated.tree_title_font_size,'30');
  assert.equal(updated.clan_name_font_size,'72');
  assert.equal(updated.tree_subtitle,'Dòng một\nDòng hai');
  const html=fs.readFileSync(path.join(projectRoot,'public','index.html'),'utf8');
  const app=fs.readFileSync(path.join(projectRoot,'public','app.js'),'utf8');
  const adminJs=fs.readFileSync(path.join(projectRoot,'public','admin.js'),'utf8');
  assert.match(html,/id="heroClanName"/,'Trang công khai phải có dòng tên dòng họ riêng');
  assert.match(html,/id="statsPanel"/,'Trang công khai phải có bảng danh sách thống kê');
  assert.match(html,/id="statsSearch"/,'Danh sách thống kê phải có tìm kiếm theo tên');
  assert.match(html,/id="statsFirstPage"/,'Danh sách thống kê phải có nút nhảy trang đầu');
  assert.match(html,/id="statsLastPage"/,'Danh sách thống kê phải có nút nhảy trang cuối');
  assert.match(app,/data-stat-key/,'Các thống kê phải có hành vi bấm mở danh sách');
  assert.match(adminJs,/set_tree_title_font_size/,'Cài đặt phải cho chỉnh cỡ chữ Tiêu đề cây');
  assert.match(adminJs,/treeSubtitleEditor/,'Phụ đề phải dùng trình soạn nhiều dòng có định dạng');
  assert.match(adminJs,/data-rich-color/,'Trình soạn phải hỗ trợ màu chữ');
  assert.match(adminJs,/justifyCenter/,'Trình soạn phải hỗ trợ căn lề');
  const context={console,URLSearchParams,location:{search:''},window:{addEventListener:()=>{}},document:{documentElement:{style:{setProperty:()=>{}}}},Intl,Date,setInterval:()=>0,clearInterval:()=>{},history:{}};
  vm.createContext(context); vm.runInContext(app,context);
  assert.equal(vm.runInContext(`personAgeYears({age_years:null,birth_date:''})`,context),null,'Người chưa rõ tuổi không được coi là 0 tuổi');
  assert.ok(vm.runInContext(`statsPersonSort({age_years:20,level:1,full_name:'Trẻ'},{age_years:70,level:1,full_name:'Lớn'})`,context)>0,'Danh sách thống kê phải xếp tuổi lớn trước tuổi nhỏ');
  assert.ok(vm.runInContext(`statsPersonAlphaSort({full_name:'Bình'},{full_name:'An'})`,context)>0,'Nhóm Không rõ phải sắp xếp theo tên A-Z');
  assert.equal(vm.runInContext(`normalizeStatsSearch('Nguyễn Đặng')`,context),'nguyen dang','Tìm kiếm tên phải hỗ trợ bỏ dấu tiếng Việt');
  store.db.close();
  console.log('hero-stats-regression: OK');
}finally{fs.rmSync(tmp,{recursive:true,force:true});}
